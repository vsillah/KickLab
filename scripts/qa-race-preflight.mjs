import {createRequire} from 'node:module';
import {existsSync,mkdirSync,writeFileSync} from 'node:fs';
import {join,resolve} from 'node:path';
const {chromium}=createRequire(import.meta.url)('playwright');
const out=resolve(process.argv[2]||'qa-artifacts/race-preflight');mkdirSync(out,{recursive:true});
const browser=await chromium.launch({headless:true,executablePath:[process.env.KICKLAB_CHROMIUM_PATH,chromium.executablePath(),'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'].find(path=>path&&existsSync(path))});
const checks=[];
try{
  for(const [name,width,height] of [['phone',390,844],['tablet',768,1024],['desktop',1440,900]]){
    const context=await browser.newContext({viewport:{width,height},recordVideo:name==='tablet'?undefined:{dir:out,size:{width,height}}});
    const page=await context.newPage(),errors=[],external=[];
    page.on('pageerror',error=>errors.push(error.message));
    await page.route('**/*',route=>{const url=new URL(route.request().url());if(url.origin==='http://127.0.0.1:4173'||['data:','blob:'].includes(url.protocol))return route.continue();external.push(url.href);return route.abort();});
    await page.goto('http://127.0.0.1:4173/kicklab.html?raceExpansion=prototype&raceTelemetry=prototype&racePreflight=prototype&qa=preflight',{waitUntil:'domcontentloaded'});
    if(await page.locator('#profileFormSave').isVisible())await page.click('#profileFormSave');
    if(await page.locator('#profileClose').isVisible())await page.click('#profileClose');
    await page.click('#lab-tab-race');
    if(await page.locator('.race-orbit-panel button').isVisible())await page.locator('.race-orbit-panel button').click();
    await page.waitForFunction(()=>globalThis.__KICKLAB_RACE_3D__?.orbit?.done,{timeout:20000});
    await page.waitForFunction(()=>globalThis.__KICKLAB_RACE_PREFLIGHT_QA__?.state().open,{timeout:10000});
    await page.waitForFunction(()=>document.querySelector('[data-preflight-mode="drag"] video')?.readyState>=2,{timeout:12000});
    const original=await page.evaluate(()=>globalThis.__KICKLAB_RACE_PREFLIGHT_QA__.state().saved);
    await page.screenshot({path:join(out,`${name}-location.png`)});
    await page.locator('[data-preflight-mode="endurance"]').click();
    await page.click('#racePreflightNext');
    await page.waitForTimeout(350);
    await page.locator('.race-preflight-roster').evaluate(node=>node.scrollLeft=node.scrollWidth);
    await page.locator('[data-preflight-vehicle="aegis"]').click();
    const vehicle=await page.evaluate(()=>globalThis.__KICKLAB_RACE_PREFLIGHT_QA__.state());
    if(vehicle.draft.vehicle!=='aegis'||vehicle.saved.mode!==original.mode||JSON.stringify(vehicle.saved.garage)!==JSON.stringify(original.garage))throw Error(`${name} draft mutated saved profile`);
    await page.waitForFunction(()=>document.querySelector('.race-preflight-feature video')?.readyState>=2,{timeout:12000});
    await page.locator('.race-preflight-roster img').first().evaluate(img=>img.decode());
    await page.evaluate(()=>document.querySelector('#racePreflight').scrollTop=0);
    await page.screenshot({path:join(out,`${name}-vehicle.png`)});
    await page.click('#racePreflightNext');
    await page.locator('[data-preflight-part="tires"][data-preflight-value="wide"]').click();
    await page.waitForFunction(()=>document.querySelector('.race-preflight-tune-preview video')?.readyState>=2,{timeout:12000});
    await page.evaluate(()=>document.querySelector('#racePreflight').scrollTop=0);
    await page.screenshot({path:join(out,`${name}-tuning.png`)});
    await page.click('#racePreflightBack');
    if((await page.evaluate(()=>globalThis.__KICKLAB_RACE_PREFLIGHT_QA__.state().draft.garage.tires))!=='wide')throw Error(`${name} tune lost on back`);
    await page.click('#racePreflightNext');
    await page.click('#racePreflightNext');
    await page.waitForFunction(()=>document.querySelector('.race-preflight-grid-car video')?.readyState>=2,{timeout:12000});
    await page.evaluate(()=>document.querySelector('#racePreflight').scrollTop=0);
    await page.screenshot({path:join(out,`${name}-grid.png`)});
    const overflow=await page.evaluate(()=>Math.max(0,document.documentElement.scrollWidth-innerWidth));
    if(overflow>1)throw Error(`${name} horizontal overflow ${overflow}px`);
    await page.click('#racePreflightNext');
    await page.waitForFunction(()=>document.querySelector('#racePreflight').hidden,{timeout:10000});
    const orbit=await page.evaluate(()=>globalThis.__KICKLAB_RACE_3D__?.orbit);
    if(!['orbit','transition','done'].includes(orbit?.phase))throw Error(`${name} orbit handoff missing: ${JSON.stringify(orbit)}`);
    if(await page.locator('.race-orbit-panel button').isVisible())await page.locator('.race-orbit-panel button').click();
    await page.waitForFunction(()=>['count','run'].includes(globalThis.__KICKLAB_RACE_MODES_QA__?.state().phase),{timeout:30000});
    const launched=await page.evaluate(()=>({preflight:globalThis.__KICKLAB_RACE_PREFLIGHT_QA__.state(),mode:globalThis.__KICKLAB_RACE_MODES_QA__.state()}));
    if(launched.preflight.saved.mode!=='endurance'||launched.mode.car!=='aegis'||launched.mode.garage.tires!=='wide'||external.length||errors.length)throw Error(`${name} launch: ${JSON.stringify({launched,external,errors}).slice(0,1500)}`);
    checks.push({name,width,height,overflow,vehicle:launched.mode.car,mode:launched.preflight.saved.mode,orbit:orbit.phase,egress:external.length,errors});
    await context.close();
  }
  writeFileSync(join(out,'report.json'),JSON.stringify(checks,null,2));
  console.log(JSON.stringify(checks,null,2));
}finally{await browser.close();}
