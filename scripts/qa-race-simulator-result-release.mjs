// The last held pedal release must not activate a newly revealed result action.
import {createRequire} from 'node:module';
import {execFileSync} from 'node:child_process';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
const {chromium}=createRequire(import.meta.url)('playwright');
const head=execFileSync('git',['rev-parse','HEAD'],{encoding:'utf8'}).trim();
if(process.env.KICKLAB_QA_HEAD!==head)throw Error('Bind to exact worktree head');
const base=new URL(process.argv[2]||'http://127.0.0.1:4173/kicklab.html');
if(!['127.0.0.1','localhost'].includes(base.hostname))throw Error('Use localhost');
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
if(hash(Buffer.from(await(await fetch(base)).arrayBuffer()))!==hash(readFileSync('dist/kicklab.html')))throw Error('Served build differs from exact local artifact');
const browser=await chromium.launch({headless:true,executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
const context=await browser.newContext({viewport:{width:390,height:844},reducedMotion:'reduce'});
const page=await context.newPage(),errors=[],external=[];
page.on('pageerror',error=>errors.push(error.message));
await page.route('**/*',route=>{const url=route.request().url();if(url.startsWith(base.origin+'/')||url.startsWith('data:')||url.startsWith('blob:'))route.continue();else{external.push(url);route.abort();}});
for(const flag of ['raceExpansion','racePreflight','raceTelemetry','raceSimulator'])base.searchParams.set(flag,'prototype');
base.searchParams.set('raceResultsQA','1');base.searchParams.set('rev',head);
await page.goto(base.href);
if(await page.locator('#profileFormSave').isVisible())await page.locator('#profileFormSave').click();
if(await page.locator('#profileClose').isVisible())await page.locator('#profileClose').click();
await page.locator('#lab-tab-race').click();await page.locator('#racePreflight').waitFor({state:'visible'});
await page.locator('[data-preflight-venue="highland"]').click();for(let i=0;i<3;i++)await page.locator('#racePreflightNext').click();
await page.locator('[data-preflight-control="simulator"]').click();await page.locator('#racePreflightNext').click();await page.locator('#racePreflight').waitFor({state:'hidden'});
const skip=page.locator('.race-orbit-panel button');if(await skip.isVisible())await skip.click();
await page.waitForFunction(()=>window.__KICKLAB_RACE_MODES_QA__?.state().phase==='run',null,{timeout:30000});
const pedal=await page.locator('#simGas').boundingBox();if(!pedal)throw Error('Live Simulator pedal missing');
await page.mouse.move(pedal.x+pedal.width/2,pedal.y+pedal.height-5);await page.mouse.down();
const held=await page.evaluate(()=>window.__KICKLAB_RACE_SIMULATOR_QA__.state().inputs.gas);
await page.evaluate(()=>window.__KICKLAB_RACE_RESULTS_QA__.scenario({outcome:'pass',replay:'both'}));
await page.mouse.up();await page.waitForTimeout(100);
const settled=await page.evaluate(()=>({result:!document.querySelector('#results').hidden,replayBar:!document.querySelector('#rbar').hidden,deck:getComputedStyle(document.querySelector('.stage>.control-deck')).display,inputs:window.__KICKLAB_RACE_SIMULATOR_QA__.state().inputs}));
if(!held||!settled.result||settled.replayBar||settled.deck!=='none'||Object.values(settled.inputs).some(Boolean))errors.push(`Held release activated result: ${JSON.stringify({held,settled})}`);
await page.locator('#raceReplayFallback').click();if(!await page.locator('#rbar').isVisible())errors.push('Intentional Replay click blocked');
await page.locator('#rbExit').click();if(await page.locator('#rbar').isVisible())errors.push('Replay exit blocked');
await context.close();await browser.close();
console.log(JSON.stringify({head,held,settled,errors,external},null,2));
if(errors.length||external.length)process.exitCode=1;
