import {createRequire} from 'node:module';
import {existsSync,mkdirSync,statSync} from 'node:fs';
import {join,resolve} from 'node:path';
import {spawnSync} from 'node:child_process';

const {chromium}=createRequire(import.meta.url)('playwright');
const base=process.argv[2]||'http://127.0.0.1:63336/pages/index.html';
const out=resolve(process.argv[3]||'qa-artifacts/race-home-return');
const head=process.env.KICKLAB_QA_HEAD;
if(!head)throw Error('Set KICKLAB_QA_HEAD to the reviewed commit.');
mkdirSync(out,{recursive:true});
const browser=await chromium.launch({headless:true,executablePath:[process.env.KICKLAB_CHROMIUM_PATH,chromium.executablePath(),'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'].find(path=>path&&existsSync(path)),args:['--enable-webgl']});
const context=await browser.newContext({viewport:{width:1280,height:800},deviceScaleFactor:1,recordVideo:{dir:out,size:{width:1280,height:800}}});
await context.addInitScript(()=>localStorage.setItem('impactlab.v1',JSON.stringify({gfx:'3d'})));
const page=await context.newPage(),url=new URL(base),errors=[],external=[];
url.searchParams.set('rev',head);url.searchParams.set('raceResultsQA','1');
page.on('pageerror',error=>errors.push(error.message));
await page.route('**/*',route=>{const target=route.request().url();if(target.startsWith(url.origin+'/')||target.startsWith('data:')||target.startsWith('blob:'))route.continue();else{external.push(target);route.abort();}});
try{
  await page.goto(url.toString(),{waitUntil:'domcontentloaded'});
  if(await page.locator('#profileFormSave').isVisible())await page.click('#profileFormSave');
  if(await page.locator('#profileClose').isVisible())await page.click('#profileClose');
  await page.waitForTimeout(900);
  await page.click('#lab-tab-race');
  await page.waitForFunction(()=>window.__KICKLAB_RACE_PREFLIGHT_QA__?.state().open);
  await page.waitForTimeout(1400);
  await page.click('[data-preflight-mode="hill"]');await page.waitForTimeout(750);await page.click('#racePreflightNext');
  await page.waitForTimeout(1000);await page.click('[data-preflight-vehicle="kestrel"]');await page.waitForTimeout(750);await page.click('#racePreflightNext');
  await page.waitForTimeout(900);await page.click('[data-preflight-part="brakes"][data-preflight-value="sport"]');await page.waitForTimeout(750);await page.click('#racePreflightNext');
  await page.waitForTimeout(1300);await page.click('#racePreflightNext');
  await page.locator('#racePreflight').waitFor({state:'hidden',timeout:12000});
  const orbit=page.locator('.race-orbit-panel button');if(await orbit.isVisible())await orbit.click();
  await page.waitForFunction(()=>window.__KICKLAB_RACE_MODES_QA__?.state().phase==='run',{timeout:30000});
  await page.waitForTimeout(1800);
  if(!await page.evaluate(()=>window.__KICKLAB_RACE_PREFLIGHT_QA__.finishForQA()))throw Error('Could not finish QA run');
  await page.locator('#results').waitFor({state:'visible'});await page.waitForTimeout(1700);
  await page.click('#rRaceGarage');await page.locator('#modeHome').waitFor({state:'visible'});await page.waitForTimeout(1600);
  await page.click('#lab-tab-race');
  await page.waitForFunction(()=>window.__KICKLAB_RACE_PREFLIGHT_QA__?.state().open&&window.__KICKLAB_RACE_PREFLIGHT_QA__.state().phase===0);
  await page.waitForTimeout(1800);
  const checked=await page.evaluate(()=>({head:new URLSearchParams(location.search).get('rev'),phase:window.__KICKLAB_RACE_PREFLIGHT_QA__.state().phase,draft:window.__KICKLAB_RACE_PREFLIGHT_QA__.state().draft,renderer:window.__KICKLAB_RACE_3D__?.status}));
  if(checked.head!==head||checked.phase!==0||checked.draft.mode!=='hill'||checked.draft.vehicle!=='kestrel'||checked.draft.garage.brakes!=='sport')throw Error(`Return state failed: ${JSON.stringify(checked)}`);
  if(errors.length||external.length)throw Error(`Browser errors or egress: ${JSON.stringify({errors,external})}`);
  await page.locator('[data-preflight-mode="hill"]').scrollIntoViewIfNeeded();
  await page.waitForTimeout(1300);
  await page.screenshot({path:join(out,`race-home-return-${head.slice(0,8)}.png`)});
  const raw=page.video();await page.close();await context.close();await browser.close();
  const mp4=join(out,`race-home-return-${head.slice(0,8)}.mp4`),transcode=spawnSync('ffmpeg',['-y','-i',await raw.path(),'-c:v','libx264','-pix_fmt','yuv420p','-movflags','+faststart','-an',mp4],{encoding:'utf8'});
  if(transcode.status!==0)throw Error(`ffmpeg failed: ${transcode.stderr}`);
  const probe=spawnSync('ffprobe',['-v','error','-show_entries','format=duration:stream=width,height,codec_name','-of','json',mp4],{encoding:'utf8'});
  if(probe.status!==0)throw Error(`ffprobe failed: ${probe.stderr}`);
  const info=JSON.parse(probe.stdout);
  if(statSync(mp4).size<50000||Number(info.format?.duration||0)<12)throw Error(`MP4 invalid: ${JSON.stringify(info)}`);
  console.log(JSON.stringify({mp4,bytes:statSync(mp4).size,info,checked,errors,external},null,2));
}catch(error){await context.close();await browser.close();throw error;}
