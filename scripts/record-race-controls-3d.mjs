import {createRequire} from 'node:module';
import {existsSync,mkdirSync,readdirSync,statSync} from 'node:fs';
import {resolve} from 'node:path';
import {execFileSync,spawnSync} from 'node:child_process';

const {chromium}=createRequire(import.meta.url)('playwright');
const head=execFileSync('git',['rev-parse','HEAD'],{encoding:'utf8'}).trim();
const origin=process.env.KICKLAB_QA_ORIGIN||'http://127.0.0.1:4411';
const output=resolve(process.argv[2]||`qa-artifacts/mobile-race-cockpit/${head.slice(0,7)}`);
mkdirSync(output,{recursive:true});
const browser=await chromium.launch({headless:true,executablePath:[process.env.KICKLAB_CHROMIUM_PATH,chromium.executablePath(),'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'].find(path=>path&&existsSync(path))});
const context=await browser.newContext({viewport:{width:390,height:844},deviceScaleFactor:1,recordVideo:{dir:output,size:{width:390,height:844}}});
await context.addInitScript(()=>localStorage.setItem('impactlab.v1',JSON.stringify({gfx:'3d',ch:{fight:0,race:0,kick:0},play:{fight:'ch',race:'ch',kick:'ch'}})));
const page=await context.newPage();
const errors=[];
const external=[];
page.on('pageerror',error=>errors.push(String(error)));
page.on('request',request=>{if(!request.url().startsWith(origin+'/')&&!request.url().startsWith(`blob:${origin}/`))external.push(request.url());});
const params=new URLSearchParams({raceCornerTrace:'prototype',raceTelemetry:'prototype',raceExpansion:'prototype',raceSimulator:'prototype',raceSystems:'proxy',rev:head});
const url=`${origin}/kicklab.html?${params}`;
const assert3d=async step=>{
  await page.waitForFunction(()=>window.__KICKLAB_RACE_3D__?.status==='rendering'&&window.__KICKLAB_RACE_3D__?.vehicle===true,null,{timeout:15000});
  const state=await page.evaluate(()=>({graphics:JSON.parse(localStorage.getItem('impactlab.v1')||'{}').gfx,renderer:window.__KICKLAB_RACE_3D__?.status,vehicle:window.__KICKLAB_RACE_3D__?.vehicle,canvas:window.__KICKLAB_RACE_3D__?.canvas,visible:getComputedStyle(document.querySelector('#race3')).display}));
  if(state.graphics!=='3d'||state.renderer!=='rendering'||!state.vehicle||!state.canvas||state.visible==='none')throw new Error(`${step}: ${JSON.stringify(state)}`);
  return {step,...state};
};
const states=[];
try{
  await page.goto(url,{waitUntil:'networkidle'});
  if(await page.locator('#profileClose').isVisible())await page.locator('#profileClose').click();
  await page.locator('#lab-tab-race').click();
  await page.locator('#gamePacingOverlay').waitFor({state:'hidden',timeout:20000});
  const skip=page.locator('.race-orbit-panel button');
  await skip.waitFor({state:'visible',timeout:10000});
  await skip.click();
  await page.waitForFunction(()=>window.__KICKLAB_RACE_3D__?.orbit?.done===true,null,{timeout:10000});
  await page.evaluate(()=>window.scrollTo(0,220));
  states.push(await assert3d('Classic setup'));
  await page.screenshot({path:resolve(output,'classic-3d.png')});
  await page.waitForTimeout(1000);
  await page.locator('#raceCoachSetupControls').click();
  states.push(await assert3d('Analog setup'));
  await page.screenshot({path:resolve(output,'analog-3d.png')});
  await page.waitForTimeout(1000);
  await page.locator('#raceCoachSetupSimulator').click();
  states.push(await assert3d('Simulator setup'));
  await page.screenshot({path:resolve(output,'simulator-3d.png')});
  await page.waitForTimeout(1000);
  await page.locator('#simFallbackClassic').click();
  states.push(await assert3d('Back to Classic'));
  await page.waitForTimeout(1000);
  await page.reload({waitUntil:'networkidle'});
  if(await page.locator('#profileClose').isVisible())await page.locator('#profileClose').click();
  await page.locator('#lab-tab-race').click();
  await page.locator('#gamePacingOverlay').waitFor({state:'hidden',timeout:20000});
  await skip.waitFor({state:'visible',timeout:10000});
  await skip.click();
  await page.waitForFunction(()=>window.__KICKLAB_RACE_3D__?.orbit?.done===true,null,{timeout:10000});
  await page.evaluate(()=>window.scrollTo(0,220));
  states.push(await assert3d('After reload'));
  await page.screenshot({path:resolve(output,'after-reload-3d.png')});
  await page.waitForTimeout(1000);
  await page.locator('#raceCoachSetupStart').click();
  await page.waitForFunction(()=>window.__KICKLAB_RACE_3D__?.dynamics?.state==='run',null,{timeout:15000});
  states.push(await assert3d('During run'));
  await page.screenshot({path:resolve(output,'run-3d.png')});
  await page.waitForTimeout(1000);
}finally{
  await context.close();
  await browser.close();
}
const webm=readdirSync(output).filter(name=>name.endsWith('.webm')).map(name=>resolve(output,name)).sort((a,b)=>statSync(b).mtimeMs-statSync(a).mtimeMs)[0];
const mp4=resolve(output,`${head.slice(0,7)}-race-controls-3d.mp4`);
const encode=spawnSync('ffmpeg',['-y','-loglevel','error','-i',webm,'-c:v','libx264','-crf','20','-pix_fmt','yuv420p','-movflags','+faststart',mp4],{encoding:'utf8'});
if(encode.status!==0)throw new Error(encode.stderr);
const probe=spawnSync('ffprobe',['-v','error','-show_entries','format=duration:stream=codec_name,width,height','-of','json',mp4],{encoding:'utf8'});
if(probe.status!==0)throw new Error(probe.stderr);
if(errors.length||external.length)throw new Error(JSON.stringify({errors,external}));
console.log(JSON.stringify({head,url,mp4,states,errors,external,probe:JSON.parse(probe.stdout)},null,2));
