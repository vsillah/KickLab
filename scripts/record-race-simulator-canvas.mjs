import {createRequire} from 'node:module';
import {existsSync,mkdirSync,readdirSync,statSync} from 'node:fs';
import {resolve} from 'node:path';
import {spawnSync} from 'node:child_process';

const {chromium}=createRequire(import.meta.url)('playwright');
const out=resolve(process.argv[2]||'qa-artifacts/race-simulator/canvas-fallback');
mkdirSync(out,{recursive:true});
const browser=await chromium.launch({headless:true,executablePath:[process.env.KICKLAB_CHROMIUM_PATH,chromium.executablePath(),'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'].find(path=>path&&existsSync(path))});
const context=await browser.newContext({viewport:{width:390,height:844},deviceScaleFactor:1,recordVideo:{dir:out,size:{width:390,height:844}}});
await context.addInitScript(()=>localStorage.setItem('impactlab.v1',JSON.stringify({gfx:'2d',ch:{fight:0,race:0,kick:0},play:{fight:'ch',race:'ch',kick:'ch'}})));
const page=await context.newPage(),errors=[],external=[];
page.on('pageerror',error=>errors.push(String(error)));
page.on('request',request=>{const url=request.url();if(!url.startsWith('http://127.0.0.1:5879/')&&!url.startsWith('blob:http://127.0.0.1:5879/'))external.push(url);});
const revision=process.argv[3]||'canvas-fallback';
const url=`http://127.0.0.1:5879/kicklab.html?raceExpansion=prototype&raceSimulator=prototype&raceTelemetry=prototype&rev=${encodeURIComponent(revision)}`;
await page.goto(url,{waitUntil:'networkidle'});
if(await page.locator('#profileClose').isVisible())await page.locator('#profileClose').click();
await page.locator('#lab-tab-race').click();
await page.locator('#gamePacingOverlay').waitFor({state:'hidden',timeout:20000});
await page.locator('#raceCoachSetupSimulator').click();
await page.locator('#raceSimulator').scrollIntoViewIfNeeded();
await page.waitForTimeout(1100);
await page.screenshot({path:resolve(out,'canvas-simulator.png')});
await page.locator('#simEnable').click();
await page.waitForTimeout(700);
await page.locator('#simFallbackClassic').click();
await page.waitForTimeout(700);
await page.screenshot({path:resolve(out,'canvas-classic.png')});
const audit=await page.evaluate(()=>({canvasVisible:getComputedStyle(document.querySelector('#cv')).display!=='none',webglVisible:getComputedStyle(document.querySelector('#cv3')).display!=='none',controller:window.__KICKLAB_RACE_MODES_QA__?.state?.().controller}));
await context.close();await browser.close();
const webm=readdirSync(out).filter(name=>name.endsWith('.webm')).map(name=>resolve(out,name)).sort((a,b)=>statSync(b).mtimeMs-statSync(a).mtimeMs)[0];
const mp4=resolve(out,'race-simulator-canvas-fallback.mp4');
const encode=spawnSync('ffmpeg',['-y','-loglevel','error','-i',webm,'-c:v','libx264','-crf','20','-pix_fmt','yuv420p','-movflags','+faststart',mp4],{encoding:'utf8'});
if(encode.status!==0)throw new Error(encode.stderr);
const probe=spawnSync('ffprobe',['-v','error','-show_entries','format=duration:stream=codec_name,width,height,nb_frames','-of','json',mp4],{encoding:'utf8'});
if(probe.status!==0||errors.length||external.length||!audit.canvasVisible||audit.webglVisible||audit.controller!=='classic')throw new Error(JSON.stringify({probe:probe.stderr,errors,external,audit}));
console.log(JSON.stringify({url,mp4,audit,probe:JSON.parse(probe.stdout)},null,2));
