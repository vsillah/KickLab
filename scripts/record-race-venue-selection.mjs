// Privacy-safe exact-head walkthrough of Highland, Marine and Forest preflight.
import {createRequire} from 'node:module';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {existsSync,mkdirSync,readFileSync,writeFileSync} from 'node:fs';
import {join,resolve} from 'node:path';
const {chromium}=createRequire(import.meta.url)('playwright');
const head=process.env.KICKLAB_QA_HEAD;
if(!/^[0-9a-f]{40}$/.test(head||''))throw Error('KICKLAB_QA_HEAD must bind the exact commit');
if(execFileSync('git',['rev-parse','HEAD'],{encoding:'utf8'}).trim()!==head||execFileSync('git',['status','--porcelain'],{encoding:'utf8'}).trim())throw Error('Exact-head capture requires a clean checkout at KICKLAB_QA_HEAD');
const base='http://127.0.0.1:4173/pages/index.html',out=resolve('qa-artifacts/venue-selection');
mkdirSync(out,{recursive:true});
const hash=value=>createHash('sha256').update(value).digest('hex');
const local=readFileSync('dist/pages/index.html'),remote=Buffer.from(await(await fetch(`${base}?rev=${head}`)).arrayBuffer());
if(hash(local)!==hash(remote))throw Error('Incorrect localhost Pages artifact');
const browser=await chromium.launch({headless:true,executablePath:[process.env.KICKLAB_CHROMIUM_PATH,chromium.executablePath(),'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'].find(path=>path&&existsSync(path)),args:['--enable-webgl','--use-gl=angle','--use-angle=swiftshader']});
const context=await browser.newContext({viewport:{width:1280,height:800},recordVideo:{dir:out,size:{width:1280,height:800}},reducedMotion:'no-preference'});
const page=await context.newPage(),video=page.video(),external=[],errors=[];
page.on('pageerror',error=>errors.push(error.message));
await page.route('**/*',route=>{const url=route.request().url();if(url.startsWith('http://127.0.0.1:4173/')||url.startsWith('blob:')||url.startsWith('data:'))route.continue();else{external.push(url);route.abort();}});
const url=`${base}?raceExpansion=prototype&raceTelemetry=prototype&raceProgression=prototype&racePreflight=prototype&rev=${head}`;
try{
  await page.goto(url,{waitUntil:'domcontentloaded'});
  if(await page.locator('#profileFormSave').isVisible())await page.click('#profileFormSave');
  if(await page.locator('#profileClose').isVisible())await page.click('#profileClose');
  await page.evaluate(()=>window.__KICKLAB_RACE_PROGRESSION_QA__.unlockForQA(2));
  await page.click('#lab-tab-race');await page.locator('#racePreflight').waitFor({state:'visible'});
  await page.waitForTimeout(1600);
  await page.click('[data-preflight-venue="highland"]');await page.waitForTimeout(700);
  await page.click('[data-preflight-mode="hill"]');await page.waitForTimeout(1400);
  await page.click('#racePreflightBack');await page.waitForTimeout(500);
  await page.click('[data-preflight-venue="marine"]');await page.waitForTimeout(1500);
  await page.click('#racePreflightNext');await page.waitForTimeout(800);
  if(/switchback|climb/i.test(await page.locator('.race-preflight-showroom').innerText()))throw Error('Marine vehicle copy fell back to Highland');
  await page.click('#racePreflightNext');await page.waitForTimeout(800);
  await page.click('#racePreflightNext');await page.waitForTimeout(1100);
  const marineGrid=await page.locator('.race-preflight-grid-brief').innerText();
  if(!marineGrid.includes('Marine Terrace · Damp corner')||marineGrid.includes('Switchback corner'))throw Error('Marine grid route wording does not match its canonical venue');
  for(let step=0;step<4;step++)await page.click('#racePreflightBack');
  await page.waitForTimeout(650);
  await page.click('[data-preflight-venue="forest"]');await page.waitForTimeout(1500);
  await page.click('#racePreflightNext');await page.waitForTimeout(700);
  if(/switchback|climb/i.test(await page.locator('.race-preflight-showroom').innerText()))throw Error('Forest vehicle copy fell back to Highland');
  await page.click('#racePreflightNext');await page.waitForTimeout(700);
  await page.click('#racePreflightNext');await page.waitForTimeout(1200);
  const forestGrid=await page.locator('.race-preflight-grid-brief').innerText();
  if(!forestGrid.includes('Forest Lantern Descent · Descending left turn')||forestGrid.includes('Switchback corner'))throw Error('Forest grid route wording does not match its canonical venue');
  await page.click('#racePreflightNext');await page.locator('#racePreflight').waitFor({state:'hidden',timeout:15000});
  const orbit=page.locator('.race-orbit-panel button');if(await orbit.isVisible())await orbit.click();
  await page.waitForFunction(()=>window.__KICKLAB_RACE_PROGRESSION_QA__.state().raceState==='run',null,{timeout:25000});
  await page.waitForTimeout(1500);
  if(external.length||errors.length)throw Error(JSON.stringify({external,errors}));
}finally{await page.close();await context.close();await browser.close();}
const raw=await video.path(),mp4=join(out,`venue-first-${head.slice(0,12)}.mp4`);
execFileSync('ffmpeg',['-y','-i',raw,'-an','-c:v','libx264','-preset','medium','-crf','22','-pix_fmt','yuv420p','-movflags','+faststart',mp4],{stdio:'ignore'});
const probe=JSON.parse(execFileSync('ffprobe',['-v','error','-show_entries','format=duration,size:stream=codec_name,width,height','-of','json',mp4],{encoding:'utf8'}));
if(Number(probe.format?.duration)<10||probe.streams?.[0]?.codec_name!=='h264'||probe.streams?.[0]?.width!==1280||probe.streams?.[0]?.height!==800)throw Error(`MP4 playback gate failed: ${JSON.stringify(probe)}`);
const report={head,url,artifactSha256:hash(local),mp4,mp4Sha256:hash(readFileSync(mp4)),durationSeconds:Number(probe.format.duration),bytes:Number(probe.format.size),external,errors};
writeFileSync(join(out,'walkthrough-report.json'),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report,null,2));
