import { existsSync, mkdirSync, statSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { createRequire } from 'node:module';
import { spawnSync } from 'node:child_process';

const { chromium } = createRequire(import.meta.url)('playwright');
const base = process.argv[2] || 'http://127.0.0.1:5879/kicklab.html';
const before = resolve(process.argv[3]);
const out = resolve(process.argv[4] || 'qa-artifacts/race-phone-video');
const revision = process.argv[5] || 'working-tree';
mkdirSync(out, { recursive: true });
const executablePath = [process.env.KICKLAB_CHROMIUM_PATH, chromium.executablePath(), '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'].find(path => path && existsSync(path));
const browser = await chromium.launch({ headless: true, executablePath });
const context = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, recordVideo: { dir: out, size: { width: 390, height: 844 } } });
await context.addInitScript(() => {
  localStorage.setItem('impactlab.v1', JSON.stringify({ ch: { fight: 0, race: 0, kick: 0 }, play: { fight: 'ch', race: 'ch', kick: 'ch' } }));
  localStorage.setItem('impactlab.nick', 'QA Player');
});
const page = await context.newPage();
const errors = [], externalRequests = [];
page.on('pageerror', error => errors.push(String(error)));
page.on('request', request => { if (new URL(request.url()).origin !== new URL(base).origin) externalRequests.push(request.url()); });
const url = new URL(base); url.searchParams.set('raceSystems', 'proxy'); url.searchParams.set('race3d', 'checkpoint'); url.searchParams.set('rev', revision);
await page.goto(url.toString(), { waitUntil: 'networkidle' });
if (await page.locator('#profileClose').isVisible()) await page.locator('#profileClose').click();
await page.locator('#lab-tab-race').click();
await page.locator('#gamePacingOverlay').waitFor({ state: 'hidden', timeout: 12000 });
await page.waitForFunction(() => window.__KICKLAB_RACE_3D__?.status === 'rendering', null, { timeout: 12000 });
await page.locator('.stage').scrollIntoViewIfNeeded();
await page.locator('#controllerCollapseButton').click();
await page.waitForTimeout(1200);
const classic = await page.evaluate(() => ({ expanded: document.querySelector('#controllerCollapseButton').getAttribute('aria-expanded'), car: window.__KICKLAB_RACE_3D__?.composition }));
await page.locator('#analogControlsButton').click();
await page.waitForTimeout(1300);
const analog = await page.evaluate(() => ({ selected: document.querySelector('#analogControlsButton').getAttribute('aria-pressed'), car: window.__KICKLAB_RACE_3D__?.composition }));
await page.locator('#gamePacingOverlay').waitFor({ state: 'hidden', timeout: 12000 });
await page.keyboard.down('Space');
await page.waitForTimeout(700);
await page.keyboard.up('Space');
await page.waitForFunction(() => window.__KICKLAB_RACE_3D__?.dynamics?.state === 'run', null, { timeout: 12000 });
await page.keyboard.press('KeyP');
await page.waitForTimeout(800);
const paused = await page.evaluate(() => ({ state: document.querySelector('#gamePacingOverlay')?.dataset.state, visible: !document.querySelector('#gamePacingOverlay')?.hidden }));
await page.keyboard.press('KeyP');
await page.waitForTimeout(600);
const resumed = await page.evaluate(() => document.querySelector('#gamePacingOverlay')?.hidden);
await page.locator('#classicControlsButton').click();
await page.waitForTimeout(900);
await page.locator('#controllerCollapseButton').click();
await page.waitForTimeout(800);
await page.locator('#controllerCollapseButton').click();
await page.waitForTimeout(900);
const recording = page.video();
await context.close();
const raw = await recording.path();
await browser.close();

function ffmpeg(args) { const result = spawnSync('ffmpeg', args, { encoding: 'utf8' }); if (result.status !== 0) throw new Error(result.stderr.slice(-1200)); }
const beforeClip = join(out, 'before.mp4'), afterClip = join(out, 'after.mp4'), mp4 = join(out, 'race-phone-before-after.mp4');
ffmpeg(['-y', '-loop', '1', '-framerate', '30', '-t', '3', '-i', before, '-vf', 'scale=390:844', '-c:v', 'libx264', '-pix_fmt', 'yuv420p', beforeClip]);
ffmpeg(['-y', '-i', raw, '-vf', 'fps=30,scale=390:844', '-c:v', 'libx264', '-pix_fmt', 'yuv420p', afterClip]);
const list = join(out, 'concat.txt');
writeFileSync(list, `file '${beforeClip}'\nfile '${afterClip}'\n`);
ffmpeg(['-y', '-f', 'concat', '-safe', '0', '-i', list, '-c:v', 'libx264', '-pix_fmt', 'yuv420p', '-movflags', '+faststart', mp4]);
const probe = spawnSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration:stream=width,height,codec_name', '-of', 'json', mp4], { encoding: 'utf8' });
const video = JSON.parse(probe.stdout);
const report = { url: url.toString(), classic, analog, paused, resumed, errors, externalRequests, video: { path: mp4, bytes: statSync(mp4).size, ...video } };
writeFileSync(join(out, 'report.json'), JSON.stringify(report, null, 2) + '\n');
console.log(JSON.stringify(report, null, 2));
if (errors.length || externalRequests.length || !paused.visible || paused.state !== 'paused' || !resumed || statSync(mp4).size < 100_000 || Number(video.format?.duration || 0) < 7 || video.streams?.[0]?.codec_name !== 'h264') process.exitCode = 1;
