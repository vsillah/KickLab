// Reproduce the public Pages offline Race entry failure without changing product state.
import {createRequire} from 'node:module';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {resolve,join} from 'node:path';
const {chromium}=createRequire(import.meta.url)('playwright');
const head=process.env.KICKLAB_QA_HEAD;
if(!/^[a-f0-9]{40}$/.test(head||'')||execFileSync('git',['rev-parse','HEAD'],{encoding:'utf8'}).trim()!==head)throw Error('Set KICKLAB_QA_HEAD to exact HEAD');
const url=new URL(process.argv[2]||'http://127.0.0.1:4173/pages/index.html');
if(!['127.0.0.1','localhost'].includes(url.hostname)||url.pathname!=='/pages/index.html')throw Error('Use localhost Pages');
url.searchParams.set('rev',head);
const sha=value=>createHash('sha256').update(value).digest('hex'),artifactSha256=sha(readFileSync('dist/pages/index.html'));
if(sha(Buffer.from(await(await fetch(url)).arrayBuffer()))!==artifactSha256)throw Error('Served Pages HTML differs from build');
const out=resolve('qa-artifacts/public-offline-race-entry');mkdirSync(out,{recursive:true});
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:390,height:844},hasTouch:true,reducedMotion:'reduce',permissions:[]});
await context.addInitScript(()=>localStorage.setItem('impactlab.v1',JSON.stringify({gfx:'2d'})));
const page=await context.newPage(),requests=[],failedRequests=[],pageErrors=[],popups=[],downloads=[];
page.on('request',r=>requests.push({url:r.url(),method:r.method(),type:r.resourceType()}));
page.on('requestfailed',r=>failedRequests.push({url:r.url(),reason:r.failure()?.errorText||''}));
page.on('pageerror',e=>pageErrors.push(e.message));page.on('popup',p=>popups.push(p.url()));page.on('download',d=>downloads.push(d.suggestedFilename()));
await page.route('**/*',route=>{const target=route.request().url();if(target.startsWith(url.origin+'/')||target.startsWith('blob:')||target.startsWith('data:'))route.continue();else{failedRequests.push({url:target,reason:'external blocked'});route.abort();}});
await page.goto(url.toString(),{waitUntil:'domcontentloaded'});
if(await page.locator('#profileFormSave').isVisible())await page.locator('#profileFormSave').click();
if(await page.locator('#profileClose').isVisible())await page.locator('#profileClose').click();
await context.setOffline(true);
await page.locator('#lab-tab-fight').click();await page.locator('#game-cockpit').waitFor({state:'visible'});
await page.screenshot({path:join(out,'offline-fight.png')});
await page.locator('#orientationDetailToggle').click();await page.locator('#modeHomeButton').click();
await page.locator('#modeHome').waitFor({state:'visible'});
await page.locator('#lab-tab-race').click();
await page.waitForURL('chrome-error://chromewebdata/',{timeout:15000});
await page.screenshot({path:join(out,'offline-race-error.png')});
const flagged=failedRequests.find(r=>r.url.startsWith(url.origin+'/pages/index.html?')&&r.url.includes('racePreflight=prototype'));
const report={head,artifactSha256,viewport:'390x844',motion:'reduce',gfx:'2d',initialUrl:url.toString(),fightOffline:true,raceDestination:page.url(),flaggedNavigation:flagged||null,requestCount:requests.length,failedRequests,pageErrors,popups,downloads};
await context.close();await browser.close();
writeFileSync(join(out,'report.json'),JSON.stringify(report,null,2)+'\n');console.log(JSON.stringify(report,null,2));
if(!flagged||report.raceDestination!=='chrome-error://chromewebdata/'||requests.some(r=>!r.url.startsWith(url.origin+'/'))||popups.length||downloads.length)throw Error('Reproduction changed or network boundary failed');
process.exitCode=1;
