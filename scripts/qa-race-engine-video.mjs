import {existsSync,readFileSync,writeFileSync,statSync} from 'node:fs';
import {resolve,join} from 'node:path';
import {spawnSync} from 'node:child_process';
const out=resolve(process.argv[2]||'qa-artifacts/race-engine-feedback/exact-head');
const report=JSON.parse(readFileSync(join(out,'report.json'),'utf8'));
if(report.checks.some(check=>!check.pass)||report.errors.length||report.external.length)throw Error('Race engine QA report is not clean');
const stages=['normal','warming','hot','critical','power-loss','cooling'];
const images=stages.map(stage=>join(out,`1440-classic-${stage}.png`));
for(const image of images)if(!existsSync(image))throw Error(`Missing exact-head frame: ${image}`);
const quote=path=>`'${path.replaceAll("'","'\\''")}'`;
const list=join(out,'walkthrough-frames.txt');writeFileSync(list,images.map(image=>`file ${quote(image)}\nduration 3.5\n`).join('')+`file ${quote(images.at(-1))}\n`);
const mp4=join(out,`race-engine-feedback-${report.revision.slice(0,12)}.mp4`);
const ffmpeg=spawnSync('ffmpeg',['-y','-f','concat','-safe','0','-i',list,'-vf','fps=30,scale=1440:1000:force_original_aspect_ratio=decrease,pad=1440:1000:(ow-iw)/2:(oh-ih)/2:color=#081423','-c:v','libx264','-preset','medium','-crf','20','-pix_fmt','yuv420p','-movflags','+faststart',mp4],{encoding:'utf8'});
if(ffmpeg.status!==0)throw Error(ffmpeg.stderr.slice(-2000));
const probe=spawnSync('ffprobe',['-v','error','-show_entries','format=duration:stream=codec_name,width,height,nb_frames','-of','json',mp4],{encoding:'utf8'});
if(probe.status!==0)throw Error(probe.stderr);
const details=JSON.parse(probe.stdout),duration=Number(details.format.duration),video=details.streams.find(stream=>stream.codec_name==='h264');
if(!video||video.width!==1440||video.height!==1000||duration<20||statSync(mp4).size<100000)throw Error('Walkthrough encoding failed validation');
console.log(JSON.stringify({mp4,duration,bytes:statSync(mp4).size,video,revision:report.revision},null,2));
